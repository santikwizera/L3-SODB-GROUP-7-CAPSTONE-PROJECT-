const DEFAULT_LANG = 'en';
let currentLang = localStorage.getItem('siteLang') || DEFAULT_LANG;

function translate(key) {
  return TRANSLATIONS[currentLang]?.[key] || TRANSLATIONS[DEFAULT_LANG]?.[key] || key;
}

function setLanguage(lang) {
  if (!TRANSLATIONS[lang]) return;
  currentLang = lang;
  localStorage.setItem('siteLang', lang);
  document.documentElement.lang = lang;
  updateLanguageToggles();
  applyTranslations();
}

function updateLanguageToggles() {
  document.querySelectorAll('.lang-toggle').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
  });
  document.querySelectorAll('.lang-selector').forEach(select => {
    select.value = currentLang;
  });
}

function addLanguageListeners() {
  document.querySelectorAll('.lang-selector').forEach(select => {
    select.addEventListener('change', event => {
      setLanguage(event.target.value);
    });
  });
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n-key]').forEach(el => {
    const key = el.dataset.i18nKey;
    if (!key) return;
    const value = translate(key);
    if (el.hasAttribute('data-i18n-html')) {
      el.innerHTML = value;
    } else {
      el.textContent = value;
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (!key) return;
    el.placeholder = translate(key);
  });

  const titleKey = document.body.dataset.titleKey;
  if (titleKey) {
    document.title = translate(titleKey);
  }
}

function switchLanguage(lang) {
  setLanguage(lang);
}

window.translate = translate;
window.addEventListener('DOMContentLoaded', () => {
  addLanguageListeners();
  setLanguage(currentLang);
});
